import { readFileSync, writeFileSync } from 'node:fs'

// Generate wire models from FastAPI's JSON Schema without a runtime dependency.
const input = new URL('../../contracts/openapi.json', import.meta.url)
const output = new URL('../src/api/backend.d.ts', import.meta.url)
const contract = JSON.parse(readFileSync(input, 'utf8'))
function typeOf(s) {
  if (s.$ref) return `BackendSchemas[${JSON.stringify(s.$ref.split('/').pop())}]`
  if (s.enum) return s.enum.map((v) => JSON.stringify(v)).join(' | ')
  if ('const' in s) return JSON.stringify(s.const)
  if (s.anyOf || s.oneOf) return (s.anyOf ?? s.oneOf).map(typeOf).join(' | ')
  if (s.allOf) return s.allOf.map(typeOf).join(' & ')
  if (Array.isArray(s.type)) return s.type.map((type) => typeOf({ ...s, type })).join(' | ')
  if (s.type === 'null') return 'null'
  if (s.type === 'integer' || s.type === 'number') return 'number'
  if (s.type === 'string' || s.type === 'boolean') return s.type
  if (s.type === 'array') return s.prefixItems ? `[${s.prefixItems.map(typeOf).join(', ')}]` : `(${typeOf(s.items ?? {})})[]`
  if (s.type === 'object' || s.properties) {
    const props = Object.entries(s.properties ?? {}).map(([key, value]) => `${JSON.stringify(key)}${s.required?.includes(key) ? '' : '?'}: ${typeOf(value)}`)
    if (s.additionalProperties) props.push(`[key: string]: ${s.additionalProperties === true ? 'unknown' : typeOf(s.additionalProperties)}`)
    return props.length ? `{ ${props.join('; ')} }` : 'Record<string, unknown>'
  }
  return 'unknown'
}
const models = Object.entries(contract.components.schemas).map(([name, schema]) => `  ${JSON.stringify(name)}: ${typeOf(schema)}`)
const content = `// Generated by npm run api:generate from contracts/openapi.json. Do not edit.\nexport interface BackendSchemas {\n${models.join('\n')}\n}\n`
if (process.argv.includes('--check')) {
  if (readFileSync(output, 'utf8') !== content) throw new Error('API types are stale: run npm run api:generate')
} else writeFileSync(output, content)
